"""Synthetic test cabinet that mirrors the layout in Emerson's EAGLE EYE problem statement.
Generates the three engineering inputs: GA drawing (vector PDF), wire list (xlsx), QC checklist (xlsx).
All coordinates are in mm on a 600 x 800 backplate, origin top-left.
"""
import copy, os
from reportlab.pdfgen import canvas
from reportlab.lib.colors import HexColor
from openpyxl import Workbook

W, H = 600, 800

def base_layout():
    devs = []
    devs.append(dict(tag="PS11", type="psu", x=30, y=40, w=95, h=125))
    devs.append(dict(tag="PS12", type="psu", x=140, y=40, w=95, h=125))
    devs.append(dict(tag="D12", type="controller", x=250, y=40, w=70, h=125))
    for i in range(4):
        devs.append(dict(tag=f"CB4{i+1}", type="breaker", group="RAIL-1",
                         x=340 + i * 34, y=55, w=30, h=95))
    for i in range(4):
        devs.append(dict(tag=f"1CBP0{i+1}", type="baseplate", x=30, y=250 + i * 112, w=270, h=92))
    devs.append(dict(tag="PE", type="earth", x=30, y=735, w=540, h=30))
    terms = []
    for i in range(8):
        terms.append(dict(tag=f"X3:{i+1}", n=i + 1, x=400, y=262 + i * 54, w=50, h=26))
    return devs, terms

DESTS = ["CB41-2", "CB42-2", "CB43-2", "CB44-2", "PS11+", "PS11-", "D12-L", "PE-1"]
COLOURS = ["BN", "BN", "BN", "BN", "RD", "BK", "BU", "GNYE"]

def wire_list():
    return [dict(wire=f"W{100+i+1}", terminal=f"X3:{i+1}", to=DESTS[i],
                 ferrule=f"X3-{i+1}/{DESTS[i]}", colour=COLOURS[i]) for i in range(8)]

def label_box(d):
    """Where the device label (name tag) physically sits, mm. Same place the tag is printed on the GA."""
    if d["type"] == "breaker":
        return (d["x"] + 1, d["y"] + 4, d["w"] - 2, 11)
    if d["type"] == "earth":
        return (d["x"] + 6, d["y"] + 9, 26, 12)
    if d["type"] == "baseplate":
        return (d["x"] + 8, d["y"] + 6, 56, 13)
    return (d["x"] + 8, d["y"] + 6, min(d["w"] - 16, 52), 13)

def ferrule_box(t):
    return (t["x"] + t["w"] + 6, t["y"] + t["h"] / 2 - 6.5, 62, 13)

def wire_sample_box(t):
    return (t["x"] + t["w"] + 74, t["y"] + t["h"] / 2 - 2.5, 40, 5)

# ---------------------------------------------------------------- GA drawing (vector PDF)
def write_ga_pdf(path):
    devs, terms = base_layout()
    s = 0.9  # pt per mm  -> page 540 x 720 pt + title block
    c = canvas.Canvas(path, pagesize=(W * s + 40, H * s + 90))
    ox, oy = 20, 70
    def R(x, y, w, h, **kw):
        c.rect(ox + x * s, oy + (H - y - h) * s, w * s, h * s, **kw)
    def T(x, y, txt, size, font="Helvetica-Bold"):
        c.setFont(font, size)
        c.drawString(ox + x * s, oy + (H - y) * s, txt)
    blue = HexColor("#1f4fa8")
    c.setStrokeColor(blue); c.setFillColor(blue); c.setLineWidth(1.2)
    R(0, 0, W, H)
    c.setLineWidth(0.6)
    R(0, 185, W, 40); R(330, 225, 40, 500)                       # wiring ducts
    for d in devs:
        c.setLineWidth(1.0); R(d["x"], d["y"], d["w"], d["h"])
        lx, ly, lw, lh = label_box(d)
        T(lx + 1, ly + lh - 2, d["tag"], 8.5 if d["type"] == "breaker" else 10)
    c.setLineWidth(0.8); R(395, 255, 60, 8 * 54)
    T(398, 252, "X3", 10)
    for t in terms:
        R(t["x"], t["y"], t["w"], t["h"])
        T(t["x"] + 3, t["y"] + 17, t["tag"], 7, "Helvetica")
    # title block
    c.setFont("Helvetica-Bold", 11)
    c.drawString(20, 45, "GA DRAWING  |  CABINET EE-DEMO-01  |  BACKPLATE 600 x 800 mm")
    c.setFont("Helvetica", 8)
    c.drawString(20, 30, "Synthetic test cabinet generated by Team EAGLE EYE for proof-of-concept. Rev A.")
    c.save()

def write_wire_list(path):
    wb = Workbook(); ws = wb.active; ws.title = "WireList"
    ws.append(["Wire No", "From (Terminal)", "To", "Ferrule text (X3 end)", "Colour"])
    for w in wire_list():
        ws.append([w["wire"], w["terminal"], w["to"], w["ferrule"], w["colour"]])
    wb.save(path)

def checklist_items():
    devs, terms = base_layout()
    items = []
    for d in devs:
        items.append(dict(id=f"GA-{d['tag']}", check="GA", target=d["tag"], desc=f"{d['tag']} present ({d['type']})"))
    items.append(dict(id="ORD-RAIL-1", check="ORDER", target="RAIL-1", desc="Breaker order on RAIL-1"))
    for d in devs:
        items.append(dict(id=f"LBL-{d['tag']}", check="LABEL", target=d["tag"], desc=f"{d['tag']} device label"))
    for w in wire_list():
        items.append(dict(id=f"FER-{w['terminal']}", check="FERRULE", target=w["terminal"], desc=f"Ferrule on {w['terminal']} wire"))
    for w in wire_list():
        items.append(dict(id=f"COL-{w['terminal']}", check="COLOUR", target=w["terminal"], desc=f"Wire colour at {w['terminal']}"))
    return items

def write_checklist(path):
    wb = Workbook(); ws = wb.active; ws.title = "QC Checklist"
    ws.append(["Item ID", "Check", "Description", "Expected", "Found", "Result", "Evidence"])
    for it in checklist_items():
        ws.append([it["id"], it["check"], it["desc"], "", "", "", ""])
    wb.save(path)

if __name__ == "__main__":
    out = os.path.join(os.path.dirname(__file__), "inputs"); os.makedirs(out, exist_ok=True)
    write_ga_pdf(f"{out}/GA_EE-DEMO-01.pdf")
    write_wire_list(f"{out}/WireList_EE-DEMO-01.xlsx")
    write_checklist(f"{out}/QC_Checklist_EE-DEMO-01.xlsx")
    print("inputs written", len(checklist_items()), "checklist items")
